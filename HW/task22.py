# приветствие "Hello", которое только что записали в файл text.txt

f = open("text.txt", "w+t")
f.write("Hello\n")

# Перематываем курсор в самое начало файла (позиция 0)
f.seek(0)

# Читаем всё содержимое файла и выводим его
content = f.read()
print(content)

f.close()
